class QEditor(Widget, can_focus=True):
    """A custom widget that looks like a text editor but acts as a form."""
    
    focused_line_idx = reactive(0)
    cursor_pos = reactive(0)
    cursor_visible = reactive(True)
    
    class FieldFocused(events.Message):
        """Emitted when a new field is focused."""
        def __init__(self, key: str) -> None:
            self.key = key
            super().__init__()

    def __init__(self, template, *args, **kwargs):
        super().__init__(*args, **kwargs)
        self.template = copy.deepcopy(template)

    def on_mount(self) -> None:
        self.set_interval(0.5, self.toggle_cursor)
        
        # Auto-focus the first editable field
        for i, item in enumerate(self.template):
            if item.get("type") == "field":
                self.focused_line_idx = i
                val = item.get("value", "")
                self.cursor_pos = len(val) if "\n" not in val else len(val.split("\n")[-1])
                break
        
    def toggle_cursor(self) -> None:
        self.cursor_visible = not self.cursor_visible
                
    def get_content_height(self, container, viewport, width) -> int:
        total_lines = 0
        for item in self.template:
            if item.get("type") == "field":
                val = item.get("value", "")
                total_lines += val.count("\n") + 1
            else:
                total_lines += 1
        return total_lines

    def watch_focused_line_idx(self, old_idx: int, new_idx: int) -> None:
        if 0 <= new_idx < len(self.template):
            line = self.template[new_idx]
            if line.get("type") == "field":
                self.cursor_pos = len(line.get("value", ""))
            self.post_message(self.FieldFocused(line.get("key", "empty")))
        
        # Manually force the parent VerticalScroll to scroll with a margin
        if getattr(self, "parent", None) and hasattr(self.parent, "scroll_y"):
            scroll_y = self.parent.scroll_y
            viewport_height = self.parent.size.height
            margin = 5
            
            target_y = scroll_y
            if new_idx < scroll_y + margin:
                target_y = max(0, new_idx - margin)
            elif new_idx > scroll_y + viewport_height - 1 - margin:
                target_y = new_idx - viewport_height + 1 + margin
                
            if target_y != scroll_y:
                self.parent.scroll_to(y=target_y, animate=False)

    def render(self) -> Text:
        lines = []
        for i, line in enumerate(self.template):
            line_num = f"{i+1:3d} "
            
            if line["type"] == "static":
                text_content = Text(line["text"])
            else:
                label = line["label"]
                val = line["value"]
                suffix = line.get("suffix", "")
                
                if i == self.focused_line_idx:
                    if self.cursor_visible:
                        if self.cursor_pos < len(val):
                            val_styled = Text(val[:self.cursor_pos]) + Text(val[self.cursor_pos], style="reverse") + Text(val[self.cursor_pos+1:])
                        else:
                            val_styled = Text(val) + Text(" ", style="reverse")
                    else:
                        val_styled = Text(val)
                    
                    if line.get("quote"):
                        text_content = Text(label) + Text("'") + val_styled + Text("'") + Text(suffix)
                    else:
                        text_content = Text(label) + val_styled + Text(suffix)
                else:
                    if val == "":
                        val_str = "''" if line.get("quote") else ""
                    else:
                        val_str = f"'{val}'" if line.get("quote") else val
                    text_content = Text(label) + Text(val_str, style="red bold") + Text(suffix)
                
            if i == self.focused_line_idx:
                text_content.stylize("black on white")
                
            styled_line = Text(line_num, style="dim") + text_content
            lines.append(styled_line)
            
        return Text("\n").join(lines)

    def on_key(self, event: events.Key) -> None:
        if event.key == "up":
            event.stop()
            event.prevent_default()
            if self.focused_line_idx > 0:
                self.focused_line_idx -= 1
        elif event.key == "down":
            event.stop()
            event.prevent_default()
            if self.focused_line_idx < len(self.template) - 1:
                self.focused_line_idx += 1
        elif event.key == "left":
            event.stop()
            event.prevent_default()
            line = self.template[self.focused_line_idx]
            if line.get("type") == "field" and self.cursor_pos > 0:
                self.cursor_pos -= 1
                self.cursor_visible = True
        elif event.key == "right":
            event.stop()
            event.prevent_default()
            line = self.template[self.focused_line_idx]
            if line.get("type") == "field" and self.cursor_pos < len(line.get("value", "")):
                self.cursor_pos += 1
                self.cursor_visible = True
        elif event.key == "enter":
            event.stop()
            event.prevent_default()
            line = self.template[self.focused_line_idx]
            if line.get("key") in ("atomic_positions", "atomic_species", "cell_parameters", "kpoints"):
                new_line = line.copy()
                if "value" in new_line:
                    new_line["value"] = ""
                self.template.insert(self.focused_line_idx + 1, new_line)
                self.focused_line_idx += 1
                self.cursor_pos = 0
                self.refresh(layout=True)
            else:
                if self.focused_line_idx < len(self.template) - 1:
                    self.focused_line_idx += 1
        elif event.key == "backspace":
            line = self.template[self.focused_line_idx]
            if line["type"] == "field":
                if self.cursor_pos > 0:
                    val = line["value"]
                    line["value"] = val[:self.cursor_pos - 1] + val[self.cursor_pos:]
                    self.cursor_pos -= 1
                    self.cursor_visible = True
                    self.refresh()
                elif line.get("key") in ("atomic_positions", "atomic_species", "cell_parameters", "kpoints") and sum(1 for l in self.template if l.get("key") == line.get("key")) > 1:
                    idx = self.focused_line_idx - 1
                    del self.template[self.focused_line_idx]
                    if idx >= 0:
                        self.focused_line_idx = idx
                    self.refresh(layout=True)
        elif event.key == "delete":
            line = self.template[self.focused_line_idx]
            if line["type"] == "field":
                val = line["value"]
                if self.cursor_pos < len(val):
                    line["value"] = val[:self.cursor_pos] + val[self.cursor_pos + 1:]
                    self.cursor_visible = True
                    self.refresh()
