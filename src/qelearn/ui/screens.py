    def action_next_step(self):
        workflow = getattr(self.app, 'workflow', 'scf')
        if workflow in ["band", "dos"]:
            # Retrieve the latest modified template from QEditor!
            current_template = self.query_one("QEditor").template
            
            if self.step == 1:
                # Step 1 to Step 2 (SCF to NSCF)
                import copy
                nscf_template = []
                
                # Lock fields except specific ones
                allowed_fields = ["kpoints", "nbnd", "occupations", "smearing", "degauss", "nosym", "verbosity"]
                for line_orig in current_template:
                    line = copy.deepcopy(line_orig)
                    
                    if line.get("key") == "calculation":
                        if line.get("type") == "static":
                            val = "bands" if workflow == "band" else "nscf"
                            line["text"] = f"  calculation = '{val}',"
                        else:
                            line["value"] = "bands" if workflow == "band" else "nscf"
                    elif line.get("key") == "kpoints_block":
                        line["text"] = "K_POINTS {crystal_b}" if workflow == "band" else "K_POINTS {automatic}"
                    elif line.get("key") == "kpoints":
                        if workflow == "band":
                            kpts = [
                                "4", 
                                "0.0000000000 0.0000000000 0.0000000000 20 ! Gamma", 
                                "0.5000000000 0.5000000000 0.0000000000 20 ! M", 
                                "0.3333333333 0.3333333333 0.0000000000 20 ! K", 
                                "0.0000000000 0.0000000000 0.0000000000 20 ! Gamma"
                            ]
                            line["value"] = kpts[0]
                            nscf_template.append(line)
                            for k in kpts[1:]:
                                new_kline = copy.deepcopy(line)
                                new_kline["value"] = k
                                nscf_template.append(new_kline)
                            continue # Already appended!
                        else:
                            line["value"] = "8 8 8 0 0 0"
                    
                    if line.get("type") == "field" and line.get("key") not in allowed_fields:
                        val = str(line.get("value", "")).strip()
                        if not val:
                            continue # Ignore empty fields to prevent broken static text
                            
                        val_str = ""
                        if line.get("quote"):
                            val_str = f"{line.get('label')}'{line.get('value')}'{line.get('suffix','')}"
                        else:
                            val_str = f"{line.get('label')}{line.get('value')}{line.get('suffix','')}"
                        
                        line["type"] = "static"
                        line["text"] = val_str
                    
                    nscf_template.append(line)
                
                workflow_data = {"scf_template": current_template}
                self.app.push_screen(SystemSetupScreen(template=nscf_template, step=2, workflow_data=workflow_data))
                
            elif self.step == 2:
                # Step 2 to Step 3 (NSCF to Post-processing Preview)
                prefix_val = "silicon"
                outdir_val = "./tmp"
                
                for line in current_template:
                    if line.get("key") == "prefix":
                        if line.get("type") != "static":
                            prefix_val = line.get("value", prefix_val)
                        else:
                            import re
                            m = re.search(r"'(.*?)'", line.get("text", ""))
                            if m: prefix_val = m.group(1)
                    elif line.get("key") == "outdir":
                        if line.get("type") != "static":
                            outdir_val = line.get("value", outdir_val)
                        else:
                            import re
                            m = re.search(r"'(.*?)'", line.get("text", ""))
                            if m: outdir_val = m.group(1)
                        
                if workflow == "band":
                    post_template = [
                        {"type": "static", "key": "bands_block", "text": "&BANDS"},
                        {"type": "static", "key": "prefix", "text": f"  prefix = '{prefix_val}',"},
                        {"type": "static", "key": "outdir", "text": f"  outdir = '{outdir_val}',"},
                        {"type": "static", "key": "filband", "text": "  filband = 'bands.dat',"},
                        {"type": "static", "key": "slash", "text": "/"}
                    ]
                else: # dos
                    post_template = [
                        {"type": "static", "key": "dos_block", "text": "&DOS"},
                        {"type": "static", "key": "prefix", "text": f"  prefix = '{prefix_val}',"},
                        {"type": "static", "key": "outdir", "text": f"  outdir = '{outdir_val}',"},
                        {"type": "static", "key": "fildos", "text": "  fildos = 'dos.dat',"},
                        {"type": "static", "key": "slash", "text": "/"}
                    ]
                
                workflow_data = self.workflow_data.copy()
                workflow_data["nscf_template"] = current_template
                self.app.push_screen(SystemSetupScreen(template=post_template, step=3, workflow_data=workflow_data))

