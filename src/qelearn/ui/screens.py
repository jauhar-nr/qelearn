    def on_paste(self, event: events.Paste) -> None:
        line = self.template[self.focused_line_idx]
        if line["type"] == "field":
            text = event.text.replace("\r", "")
            lines = text.split("\n")
            if line["key"] in ("atomic_positions", "atomic_species", "cell_parameters", "kpoints") and len(lines) > 1:
                val = line["value"]
                line["value"] = val[:self.cursor_pos] + lines[0] + val[self.cursor_pos:]
                for i, text_line in enumerate(lines[1:]):
                    if text_line.strip():
                        new_line = line.copy()
                        new_line["value"] = text_line
                        self.template.insert(self.focused_line_idx + i + 1, new_line)
                self.focused_line_idx += len([l for l in lines[1:] if l.strip()])
                self.cursor_pos = len(self.template[self.focused_line_idx]["value"])
            else:
                text_to_paste = text.replace("\n", " ")
                val = line["value"]
                line["value"] = val[:self.cursor_pos] + text_to_paste + val[self.cursor_pos:]
                self.cursor_pos += len(text_to_paste)
            self.refresh(layout=True)

